"""Build a retrieval benchmark with gold labels and paraphrased questions.

Why this exists: the first benchmark generated questions that copied wording
from the source chunks, so every retrieval method scored Recall@5 = 1.0 and the
benchmark could not separate the methods. This script fixes both problems:

1. Gold labels: each question stores the `gold_chunk_id` / `gold_doc_id` it was
   generated from, so Recall and MRR are exact instead of a lexical-overlap proxy.
2. Paraphrasing: Gemini is instructed to ask the question the way a worker or
   HR person would, reusing as little wording from the legal text as possible.
   This makes the benchmark hard enough to show differences between methods.

Usage (requires GEMINI_API_KEYS in .env or the environment):
    python scripts/build_benchmark.py
"""

import json
import random
import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.data.chunking import chunk_documents  # noqa: E402
from src.data.load_dataset import load_documents_from_jsonl  # noqa: E402
from src.generation.gemini_client import BatchGeminiClient  # noqa: E402

CORPUS_PATH = PROJECT_ROOT / "data/processed/labor_corpus_sample.jsonl"
OUTPUT_PATH = PROJECT_ROOT / "reports/benchmark_questions.json"
NUM_QUESTIONS = 30
RANDOM_SEED = 42
MIN_CHUNK_WORDS = 80

QUESTION_PROMPT = """Bạn tạo dữ liệu benchmark cho hệ thống tìm kiếm văn bản pháp luật lao động.

Cho đoạn văn bản pháp luật sau:
---
Tiêu đề: {title}
{text}
---

Hãy tạo MỘT câu hỏi mà người lao động hoặc nhân viên nhân sự sẽ hỏi, sao cho đoạn văn bản trên chứa câu trả lời.

YÊU CẦU QUAN TRỌNG:
- Câu hỏi phải DIỄN ĐẠT LẠI bằng ngôn ngữ đời thường, KHÔNG sao chép cụm từ dài (4 từ trở lên) từ văn bản gốc.
- Không nhắc tên văn bản, số hiệu, số điều trong câu hỏi.
- Câu hỏi phải tự nhiên, ngắn gọn (dưới 40 từ) và trả lời được chỉ bằng đoạn văn bản trên.
- Viết thêm câu trả lời tham khảo ngắn gọn (2-4 câu) dựa đúng vào đoạn văn bản.

Trả về JSON đúng định dạng:
{{"question": "...", "reference": "..."}}"""


def select_chunks(chunks, num_questions: int):
    """Pick one substantial chunk per document for diversity, then sample."""
    rng = random.Random(RANDOM_SEED)
    by_doc = {}
    for chunk in chunks:
        if len(chunk.text.split()) < MIN_CHUNK_WORDS:
            continue
        by_doc.setdefault(chunk.doc_id, []).append(chunk)
    picked = [rng.choice(doc_chunks) for doc_chunks in by_doc.values()]
    rng.shuffle(picked)
    return picked[: num_questions * 2]  # extra candidates in case some fail


def parse_json_response(raw: str) -> dict | None:
    match = re.search(r"\{.*\}", raw, flags=re.DOTALL)
    if not match:
        return None
    try:
        data = json.loads(match.group(0))
    except json.JSONDecodeError:
        return None
    if data.get("question") and data.get("reference"):
        return data
    return None


def main() -> None:
    documents = load_documents_from_jsonl(CORPUS_PATH)
    chunks = chunk_documents(documents)
    candidates = select_chunks(chunks, NUM_QUESTIONS)
    client = BatchGeminiClient()
    print(f"Corpus: {len(documents)} docs, {len(chunks)} chunks. Generating {NUM_QUESTIONS} questions...")

    items = []
    for chunk in candidates:
        if len(items) >= NUM_QUESTIONS:
            break
        prompt = QUESTION_PROMPT.format(title=chunk.title, text=chunk.text[:4000])
        try:
            raw = client.generate(prompt)
        except Exception as error:
            print(f"skip {chunk.chunk_id}: {error}")
            continue
        data = parse_json_response(raw)
        if data is None:
            print(f"skip {chunk.chunk_id}: unparsable response")
            continue
        items.append({
            "id": f"bench_{len(items) + 1:03d}",
            "question": data["question"].strip(),
            "reference": data["reference"].strip(),
            "gold_chunk_id": chunk.chunk_id,
            "gold_doc_id": chunk.doc_id,
            "gold_title": chunk.title,
        })
        print(f"[{len(items)}/{NUM_QUESTIONS}] {data['question'][:80]}")

    payload = {
        "description": "Paraphrased benchmark with gold chunk labels, generated by Gemini from labor_corpus_sample.jsonl",
        "generator_model": client.model,
        "num_questions": len(items),
        "items": items,
    }
    OUTPUT_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
